import streamlit as st

# ಪುಟದ ವಿನ್ಯಾಸ ಸೆಟ್ಟಿಂಗ್ಸ್
st.set_page_config(page_title="ಶುಭ ಮುಂಜಾನೆ! ☀️", page_icon="❤️")

# ಮುಖ್ಯ ಶೀರ್ಷಿಕೆ
st.title("ಶುಭ ಮುಂಜಾನೆ, ಬಂಗಾರ! ☀️")
st.write("ನಿಮ್ಮ ದಿನ ಅದ್ಭುತವಾಗಿರಲಿ! 🥰")

st.write("---")

# ಮುಖ್ಯ ಪ್ರಶ್ನೆ
st.subheader("ನನಗೊಂದು ವಿಷಯ ಹೇಳ್ತೀರಾ? 😉")
option = st.radio(
    "ನಿಮಗೆ ನನ್ನ ಮೇಲೆ ಪ್ರೀತಿ ಇದೆಯಾ?",
    ["ಆಯ್ಕೆ ಮಾಡಿ...", "ಹೌದು, ಪ್ರಾಣಕ್ಕಿಂತ ಹೆಚ್ಚಾಗಿ! ❤️", "ಇಲ್ಲ, ಸ್ವಲ್ಪ ಕಡಿಮೆ 😜"],
)

# ಉತ್ತರಕ್ಕೆ ತಕ್ಕಂತೆ ಪ್ರತಿಕ್ರಿಯೆ
if option == "ಹೌದು, ಪ್ರಾಣಕ್ಕಿಂತ ಹೆಚ್ಚಾಗಿ! ❤️":
    st.balloons()  # ಪರದೆಯ ಮೇಲೆ ಬಲೂನ್ ಹಾರುತ್ತವೆ
    st.success("ಐ ಲವ್ ಯೂ ಟೂ! 💖 ನಿಮಗಾಗಿ ಒಂದು ದೊಡ್ಡ ವರ್ಚುವಲ್ ಹಗ್ (Hug)! 🤗")

elif option == "ಇಲ್ಲ, ಸ್ವಲ್ಪ ಕಡಿಮೆ 😜":
    st.warning("ಅಯ್ಯೋ... ಸುಳ್ಳು ಹೇಳ್ಬೇಡಿ! ಮತ್ತೊಮ್ಮೆ ಯೋಚನೆ ಮಾಡಿ ಉತ್ತರ ಕೊಡಿ! 😤")
